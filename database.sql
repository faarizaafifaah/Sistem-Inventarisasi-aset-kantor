-- Untuk prototipe lokal:
-- Kebijakan ini mengizinkan akses tanpa login.
-- Jangan gunakan kebijakan terbuka ini untuk aplikasi produksi.
ALTER TABLE kategori ENABLE ROW LEVEL SECURITY;
ALTER TABLE aset ENABLE ROW LEVEL SECURITY;
ALTER TABLE disposal ENABLE ROW LEVEL SECURITY;
ALTER TABLE riwayat_kondisi ENABLE ROW LEVEL SECURITY;

CREATE POLICY "kategori_akses_prototipe"
ON kategori FOR ALL TO anon, authenticated
USING (true) WITH CHECK (true);

CREATE POLICY "aset_akses_prototipe"
ON aset FOR ALL TO anon, authenticated
USING (true) WITH CHECK (true);

CREATE POLICY "disposal_akses_prototipe"
ON disposal FOR ALL TO anon, authenticated
USING (true) WITH CHECK (true);

CREATE POLICY "riwayat_akses_prototipe"
ON riwayat_kondisi FOR ALL TO anon, authenticated
USING (true) WITH CHECK (true);
